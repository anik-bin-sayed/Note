const makeSheet = (id, name, rows, columns, cells = {}) => ({
  id,
  name,
  rows,
  columns,
  cells,
  styles: {},
});

const daysAgo = (days) =>
  new Date(Date.now() - days * 24 * 60 * 60 * 1000).toISOString();

const createBlankSheet = (name = "Sheet1") =>
  makeSheet(`sheet-${Math.random().toString(36).slice(2, 10)}`, name, 24, 12);

export const createBlankSpreadsheet = (name = "Untitled spreadsheet") => {
  const now = new Date().toISOString();
  const sheet = createBlankSheet();
  return {
    id: `spreadsheet-${Math.random().toString(36).slice(2, 10)}`,
    name,
    description: "A new spreadsheet",
    owner: "You",
    createdAt: now,
    updatedAt: now,
    rowCount: 24,
    columnCount: 12,
    favorite: false,
    sheets: [sheet],
    activeSheetId: sheet.id,
  };
};

